# ---------------------------------------------------------------------------
# Route: POST  /conversations/{conversation_id}/summary
# ---------------------------------------------------------------------------

@router.post(
    "/conversations/{conversation_id}/summary",
    response_model=SummaryResponse,
    status_code=status.HTTP_200_OK,
    summary="Generate conversation summary",
    description=(
        "Triggers the summarization pipeline for the specified conversation. "
        "Returns a structured title + bullet-point summary. Results are cached "
        "in Redis for 1 hour to avoid redundant LLM calls."
    ),
    tags=["summarization"],
)
async def generate_summary(
    conversation_id: Annotated[
        str,
        Path(description="UUID of the conversation to summarise."),
    ],
    body: SummaryRequest = SummaryRequest(),
    # Dependencies are overridden via app.dependency_overrides in tests
    current_user=Depends(_get_current_user),
    db=Depends(_get_db),
    model_manager=Depends(_get_model_manager),
    redis=Depends(_get_redis),
) -> SummaryResponse:
    from src.api.services.summarization import ConversationSummarizationService

    # Fetch conversation + ownership check would happen here via db
    # (omitted stub; real implementation uses db.get(Conversation, conversation_id))
    messages = await _fetch_messages(conversation_id, current_user, db)

    service = ConversationSummarizationService()
    try:
        result = await service.summarize(
            conversation_id=conversation_id,
            messages=messages,
            model_manager=model_manager,
            model_override=body.model_override,
            redis_client=redis,
        )
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail=str(exc))
    except RuntimeError as exc:
        logger.exception("Summarization error for conversation %s", conversation_id)
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail=str(exc))

    return SummaryResponse(
        conversation_id=result.conversation_id,
        title=result.title,
        bullets=[
            SummaryBulletResponse(text=b.text, importance=b.importance)
            for b in result.bullets[: body.max_bullets]
        ],
        generated_at=result.generated_at.isoformat(),
        cached=result.cached,
        model_used=result.model_used,
    )


# ---------------------------------------------------------------------------
# Route: GET  /conversations/{conversation_id}/summary
# ---------------------------------------------------------------------------

@router.get(
    "/conversations/{conversation_id}/summary",
    response_model=SummaryResponse,
    status_code=status.HTTP_200_OK,
    summary="Get cached conversation summary",
    description=(
        "Returns the most recently generated summary from Redis cache without "
        "triggering a new LLM call. Returns HTTP 404 if no summary exists yet."
    ),
    tags=["summarization"],
)
async def get_cached_summary(
    conversation_id: Annotated[
        str,
        Path(description="UUID of the conversation."),
    ],
    current_user=Depends(_get_current_user),
    redis=Depends(_get_redis),
) -> SummaryResponse:
    if redis is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Redis cache is not available. Use POST to generate a new summary.",
        )

    from src.api.services.summarization import ConversationSummarizationService

    service = ConversationSummarizationService()
    result = await service.get_cached(conversation_id=conversation_id, redis_client=redis)

    if result is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=(
                f"No cached summary found for conversation '{conversation_id}'. "
                "Use POST /summary to generate one."
            ),
        )

    return SummaryResponse(
        conversation_id=result.conversation_id,
        title=result.title,
        bullets=[
            SummaryBulletResponse(text=b.text, importance=b.importance)
            for b in result.bullets
        ],
        generated_at=result.generated_at.isoformat(),
        cached=True,
        model_used=result.model_used,
    )


