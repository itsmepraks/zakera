"""
Summarization API routes for Zakera AI Chat Agent.

Endpoints
---------
POST /api/v1/conversations/{conversation_id}/summary
    Trigger on-demand summarisation for a conversation.

GET  /api/v1/conversations/{conversation_id}/summary
    Return the most recent cached summary without re-generating.
"""

from __future__ import annotations

import logging
from typing import Annotated, Optional

from fastapi import APIRouter, Depends, HTTPException, Path, Query, status
from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)

router = APIRouter()


# ---------------------------------------------------------------------------
# Request / Response schemas (inline — avoids a circular import with schemas/)
# ---------------------------------------------------------------------------

class SummaryRequest(BaseModel):
    """Optional parameters for the summarisation POST."""

    model_override: Optional[str] = Field(
        default=None,
        description=(
            "Override the default model provider/slug for this summarisation request. "
            "E.g. 'mistral_large', 'gemini_flash'. Defaults to the server default."
        ),
        examples=["mistral_large"],
    )
    max_bullets: int = Field(
        default=5,
        ge=1,
        le=10,
        description="Maximum number of bullet points to return (1-10).",
    )


class SummaryBulletResponse(BaseModel):
    text: str
    importance: float = 1.0


class SummaryResponse(BaseModel):
    """Returned by both POST and GET endpoints."""

    conversation_id: str
    title: str = Field(description="Short descriptive title generated by the LLM.")
    bullets: list[SummaryBulletResponse] = Field(
        default_factory=list,
        description="Key bullet points extracted from the conversation.",
    )
    generated_at: str = Field(description="ISO-8601 timestamp of when the summary was created.")
    cached: bool = Field(
        default=False,
        description="True when the response was served from the Redis cache.",
    )
    model_used: str = Field(default="", description="Identifier of the model that generated this summary.")


